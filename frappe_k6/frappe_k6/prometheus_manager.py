"""
frappe_k6.frappe_k6.prometheus_manager
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Manages the central Prometheus scrape configuration.

Called whenever a Remote Server document is created, updated, or deleted.
Rebuilds prometheus.yml from all enabled Remote Server records and hot-reloads
the Prometheus process via its lifecycle API.
"""

import os
import subprocess
import urllib.request

import frappe

_MON_DIR  = os.path.join(os.path.expanduser("~"), "monitoring")
_PROM_DIR = os.path.join(_MON_DIR, "prometheus")
_CFG_PATH = os.path.join(_PROM_DIR, "prometheus.yml")
_RELOAD_URL = "http://localhost:9090/-/reload"
_CLOUD_TOKEN_PATH = os.path.join(_PROM_DIR, ".grafana_cloud_token")


# ─── Public API ───────────────────────────────────────────────────────────────

def sync_prometheus_config(doc=None, method=None):
    """
    Rebuild prometheus.yml from all enabled Remote Server records, then
    hot-reload Prometheus.  Safe to call repeatedly.
    Also callable as a Frappe doc_events hook (doc/method args are ignored).
    Does nothing unless Monitor Settings → Monitoring Mode is "Self-hosted" or "Hybrid".
    In Hybrid mode everything scraped is also forwarded to Grafana Cloud.
    """
    if not is_self_hosted():
        return
    servers = _get_enabled_servers()
    yml     = _build_prometheus_yml(servers, _cloud_forwarding())
    _write_config(yml)
    _reload_prometheus()


def is_self_hosted():
    try:
        return frappe.db.get_single_value("Monitor Settings", "monitoring_mode") in ("Self-hosted", "Hybrid")
    except Exception:
        return False


def get_server_labels():
    """Return list of (server_name, env) tuples for Grafana variable population."""
    return [(s["server_name"], s["environment"])
            for s in _get_enabled_servers()]


# ─── Internals ────────────────────────────────────────────────────────────────

def _get_enabled_servers():
    if not frappe.db.exists("DocType", "Remote Server"):
        return []
    return frappe.get_all(
        "Remote Server",
        filters={"enabled": 1},
        fields=[
            "server_name", "host", "environment",
            "is_local",
            "node_exporter_enabled", "node_exporter_port",
            "redis_exporter_enabled", "redis_exporter_port",
            "db_type", "db_exporter_enabled", "db_exporter_port",
        ],
    )


def _cloud_forwarding():
    """remote_write settings for Hybrid mode, or None. Writes the token to a 0600 file."""
    from frappe_k6.grafana_cloud import get_config, prom_push_url

    cfg = get_config()
    if cfg.mode != "Hybrid" or not cfg.prom_url:
        return None
    password_file = None
    if cfg.access_token:
        os.makedirs(_PROM_DIR, exist_ok=True)
        fd = os.open(_CLOUD_TOKEN_PATH, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(cfg.access_token)
        password_file = _CLOUD_TOKEN_PATH
    return {"url": prom_push_url(cfg.prom_url), "username": cfg.prom_user,
            "password_file": password_file, "site": frappe.local.site}


def _build_prometheus_yml(servers, cloud=None):
    """
    Build a prometheus.yml that scrapes each remote server's exporters,
    tagging every time-series with  server_name  and  env  labels.
    """
    node_targets   = []
    redis_targets  = []
    mysql_targets  = []
    pg_targets     = []

    for s in servers:
        host = "localhost" if s["is_local"] else s["host"]
        labels = (f"          server_name: {s['server_name']}\n"
                  f"          env: {s['environment'].lower()}")

        if s["node_exporter_enabled"]:
            port = s["node_exporter_port"] or 9100
            node_targets.append(
                f"      - targets: ['{host}:{port}']\n"
                f"        labels:\n{labels}"
            )

        if s["redis_exporter_enabled"]:
            port = s["redis_exporter_port"] or 9121
            redis_targets.append(
                f"      - targets: ['{host}:{port}']\n"
                f"        labels:\n{labels}"
            )

        if s["db_exporter_enabled"] and s["db_type"] not in (None, "None", ""):
            port = s["db_exporter_port"] or (9104 if s["db_type"] in ("MariaDB", "MySQL") else 9187)
            bucket = mysql_targets if s["db_type"] in ("MariaDB", "MySQL") else pg_targets
            bucket.append(
                f"      - targets: ['{host}:{port}']\n"
                f"        labels:\n{labels}"
            )

    def _job_block(job_name, target_list):
        if not target_list:
            return ""
        return (f"\n  - job_name: {job_name}\n"
                f"    static_configs:\n"
                + "\n".join(target_list) + "\n")

    yml = (
        "# Auto-generated by frappe_k6 prometheus_manager — do not edit manually\n"
        "global:\n"
        "  scrape_interval: 15s\n"
        "  evaluation_interval: 15s\n"
        + (f"  external_labels:\n    site: {cloud['site']}\n" if cloud else "")
        + "\n"
        "scrape_configs:\n"
        "  - job_name: prometheus\n"
        "    static_configs:\n"
        "      - targets: ['localhost:9090']\n"
        "\n"
        "  - job_name: frappe_k6\n"
        "    static_configs:\n"
        "      - targets: ['localhost:9200']\n"
    )
    yml += _job_block("node",           node_targets)
    yml += _job_block("redis_exporter", redis_targets)
    yml += _job_block("mysqld_exporter", mysql_targets)
    yml += _job_block("postgres_exporter", pg_targets)

    if cloud:
        yml += f"\nremote_write:\n  - url: {cloud['url']}\n"
        if cloud["username"] and cloud["password_file"]:
            yml += (f"    basic_auth:\n"
                    f"      username: '{cloud['username']}'\n"
                    f"      password_file: {cloud['password_file']}\n")

    return yml


def _write_config(yml_text):
    os.makedirs(_PROM_DIR, exist_ok=True)
    with open(_CFG_PATH, "w") as f:
        f.write(yml_text)


def _reload_prometheus():
    """Hot-reload via Prometheus lifecycle API (--web.enable-lifecycle must be set)."""
    try:
        req = urllib.request.Request(_RELOAD_URL, data=b"", method="POST")
        with urllib.request.urlopen(req, timeout=5):
            pass
        return True
    except Exception:
        try:
            subprocess.run(["curl", "-s", "-X", "POST", _RELOAD_URL],
                           timeout=5, capture_output=True)
        except Exception:
            pass
        return False
