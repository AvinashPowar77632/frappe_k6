"""
Generates a k6 JavaScript test script dynamically from a Load Test Config document.
"""

import json
import os
import tempfile

import frappe


def generate_script(config_name: str, output_json_path: str) -> str:
    """
    Generate a k6 JS script from the Load Test Config and write it to a temp file.
    Returns the path to the generated script.
    """
    cfg = frappe.get_doc("Load Test Config", config_name)
    stages = _build_stages(cfg)
    endpoints_code = _build_endpoints_code(cfg)
    think_time = float(cfg.think_time or 1.0)

    script = f"""// Auto-generated by frappe_k6 for config: {cfg.test_name}
import http from "k6/http";
import {{ check, sleep, group }} from "k6";
import {{ Trend, Rate, Counter }} from "k6/metrics";

const apiDuration = new Trend("frappe_api_duration", true);
const apiErrors   = new Rate("frappe_api_errors");
const apiCalls    = new Counter("frappe_api_calls");

export const options = {{
  stages: {json.dumps(stages, indent=2)},
  thresholds: {{
    http_req_failed:     ["rate<0.10"],
    http_req_duration:   ["p(95)<5000"],
    frappe_api_errors:   ["rate<0.10"],
  }},
}};

// ── Endpoint definitions ────────────────────────────────────────
{endpoints_code}

// ── Main VU function ────────────────────────────────────────────
export default function () {{
  runAllEndpoints();
  sleep({think_time});
}}

function recordMetrics(res) {{
  apiDuration.add(res.timings.duration);
  apiCalls.add(1);
  apiErrors.add(res.status >= 400 ? 1 : 0);
}}
"""
    tmp = tempfile.NamedTemporaryFile(
        mode="w", suffix=".js", delete=False,
        prefix=f"k6_{cfg.test_name.replace(' ', '_')}_"
    )
    tmp.write(script)
    tmp.close()
    return tmp.name


def _build_stages(cfg) -> list:
    scenario = cfg.scenario_type or "load"
    vus      = int(cfg.virtual_users or 10)
    duration = cfg.duration or "5m"
    ramp_up  = cfg.ramp_up_time or "1m"
    ramp_dn  = cfg.ramp_down_time or "30s"
    max_vus  = int(cfg.max_vus or vus * 3)

    presets = {
        "smoke":  [
            {"duration": "1m", "target": min(vus, 2)},
        ],
        "load":   [
            {"duration": ramp_up,  "target": vus},
            {"duration": duration, "target": vus},
            {"duration": ramp_dn,  "target": 0},
        ],
        "stress": [
            {"duration": ramp_up,  "target": vus},
            {"duration": "2m",     "target": max_vus // 2},
            {"duration": duration, "target": max_vus},
            {"duration": ramp_dn,  "target": 0},
        ],
        "spike":  [
            {"duration": "1m",    "target": vus},
            {"duration": "30s",   "target": max_vus},
            {"duration": "2m",    "target": max_vus},
            {"duration": "30s",   "target": vus},
            {"duration": "2m",    "target": vus},
            {"duration": ramp_dn, "target": 0},
        ],
        "soak":   [
            {"duration": ramp_up,  "target": vus},
            {"duration": duration, "target": vus},
            {"duration": ramp_dn,  "target": 0},
        ],
    }
    return presets.get(scenario, presets["load"])


def _build_endpoints_code(cfg) -> str:
    lines = ["function runAllEndpoints() {"]

    # Collect session-auth endpoints to batch under one login
    session_eps  = [ep for ep in cfg.endpoints if ep.auth_type == "Session (Frappe Login)"]
    other_eps    = [ep for ep in cfg.endpoints if ep.auth_type != "Session (Frappe Login)"]

    if session_eps:
        # Pick credentials from first session endpoint
        first = session_eps[0]
        creds = (first.auth_value or "Administrator:admin").split(":", 1)
        usr, pwd = creds[0], creds[1] if len(creds) > 1 else "admin"
        lines.append(f"""
  // ── Session login ─────────────────────────────────────────
  const loginRes = http.post(
    __ENV.K6_BASE_URL + "/api/method/login",
    JSON.stringify({{ usr: "{usr}", pwd: "{pwd}" }}),
    {{ headers: {{ "Content-Type": "application/json" }}, tags: {{ name: "login" }} }}
  );
  recordMetrics(loginRes);
  check(loginRes, {{ "login: 200": r => r.status === 200 }});
  const sid = loginRes.cookies["sid"] ? loginRes.cookies["sid"][0].value : "";
  const sessionHeaders = {{
    "Content-Type": "application/json",
    Cookie: "sid=" + sid
  }};""")

        for ep in session_eps:
            lines.append(_endpoint_call(ep, "sessionHeaders"))

    for ep in other_eps:
        headers = _build_headers(ep)
        lines.append(_endpoint_call(ep, None, custom_headers=headers))

    lines.append("}")
    return "\n".join(lines)


def _build_headers(ep) -> dict:
    headers = {"Content-Type": "application/json"}
    try:
        extra = json.loads(ep.headers or "{}")
        headers.update(extra)
    except Exception:
        pass

    auth = ep.auth_type or "None"
    val  = ep.auth_value or ""

    if auth == "Bearer Token":
        headers["Authorization"] = f"Bearer {val}"
    elif auth == "Basic Auth":
        import base64
        encoded = base64.b64encode(val.encode()).decode()
        headers["Authorization"] = f"Basic {encoded}"
    elif auth == "API Key":
        parts = val.split(":", 1)
        if len(parts) == 2:
            headers["Authorization"] = f"token {parts[0]}:{parts[1]}"
    elif auth == "Custom Header":
        try:
            custom = json.loads(val)
            headers.update(custom)
        except Exception:
            pass

    return headers


def _endpoint_call(ep, session_headers_var=None, custom_headers=None) -> str:
    method   = (ep.http_method or "GET").upper()
    url      = ep.endpoint_url or "/"
    expected = int(ep.expected_status or 200)
    name     = ep.api_name or url

    # Build query string
    try:
        params = json.loads(ep.query_params or "{}")
        if params:
            qs = "&".join(f"{k}={v}" for k, v in params.items())
            url = f"{url}?{qs}"
    except Exception:
        pass

    body = "null"
    if method in ("POST", "PUT", "PATCH") and ep.payload:
        try:
            json.loads(ep.payload)
            body = f"JSON.stringify({ep.payload})"
        except Exception:
            body = "null"

    if session_headers_var:
        headers_expr = session_headers_var
    else:
        headers_expr = json.dumps(custom_headers or {"Content-Type": "application/json"})

    opts = f'{{ headers: {headers_expr}, tags: {{ name: "{name}" }} }}'

    if method in ("GET", "DELETE"):
        call = f'http.{method.lower()}(\n      __ENV.K6_BASE_URL + "{url}",\n      {opts}\n    )'
    else:
        call = f'http.{method.lower()}(\n      __ENV.K6_BASE_URL + "{url}",\n      {body},\n      {opts}\n    )'

    return f"""
  group("{name}", () => {{
    const res = {call};
    recordMetrics(res);
    check(res, {{ "{name}: {expected}": r => r.status === {expected} }});
  }});"""
